SRC = 'English 8 — Wordly Wise (Drive folder)'


def cards(C, rows):
    for term, sp, d, hint in rows:
        card(C, term, d, hint=hint)
        C[-1]['sp'] = sp


def mc(Q, lv, text, opts, ans, hint, steps, main, tip, frm='source'):
    q(Q, lv, text, opts, ans, hint, steps, main, tip, frm=frm)


def an(Q, lv, stem, opts, ans, hint, steps, main, tip):
    q(Q, lv, stem, opts, ans, hint, steps, main, tip, frm='added', kind='analogy')


def finish(n, C, Q, words, summary, why, objectives, note, nxt):
    # Every word must be the subject or the answer of at least one question —
    # a word that is only ever a distractor is never practised (Latin v202).
    for w in words:
        hit = [x for x in Q if w.lower() in (x['q'] + ' ' + x['opts'][x['ans']]).lower()]
        assert hit, 'no question asks about ' + w
    build('ad-astra', C, Q, 'unit-ww9-%02d' % n, 'Wordly Wise Book 9 · Lesson %d' % n,
          'english', summary, why, objectives, note, nxt,
          'content/ww9-lesson-%02d.json' % n,
          'Wordly Wise 3000 Book 9, Lesson %d (Drive)' % n, SRC, libv_=1)
    # build() stamps quarter 1; these lessons are Quarter 2 work (Q2 began 10/12).
    path = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
                        'content', 'ww9-lesson-%02d.json' % n)
    d = json.load(open(path, encoding='utf-8'))
    d['records']['unit-ww9-%02d' % n]['quarter'] = 2
    io.open(path, 'w', encoding='utf-8').write(json.dumps(d, ensure_ascii=False, indent=1))


